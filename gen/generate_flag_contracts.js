#!/usr/bin/env node

// Derives, for every exported Rust helper, which of the five lazy-flag words it may READ and
// which it may WRITE, and emits src/rust/gen/flag_contracts.rs. The JIT's flag-locals mode
// (jit config idx 21) uses it to spill/reload only the words a helper can observe or change
// instead of all five around every call.
//
// The analysis is a conservative text-level call-graph closure over the crate sources. Every
// construct it cannot resolve widens the answer to "all five, both directions" (the behaviour
// with no contract at all), so an imprecise analysis costs speed, never correctness:
//   - calls into `extern` blocks (JS imports can re-enter the CPU: context switches read and
//     write EFLAGS) and calls through values (`)(`, `](`, fn-typed params, a transmute or cast
//     to a fn type) = full;
//   - a crate fn referenced as a value is treated as called by the referencing fn; a local that
//     shares a crate fn's name is not a reference unless it is called; a `use` is not a call;
//   - `if DEBUG { … }` is dead code (DEBUG = cfg!(debug_assertions)), which is why the builder
//     never consults the table in a debug build;
//   - a fn generated by a macro (`fn $name`) has no row, i.e. full sync;
//   - method calls resolve by name to every crate fn of that name; names the crate does not
//     define are std/core and cannot reach the flag globals except through crate trait impls,
//     which are folded in as an AMBIENT effect applied to every fn (operators, Drop, fmt...);
//   - a bare (non-deref) mention of a flag global before any local of that name = the pointer
//     escapes = read+write.
//
// Usage: node gen/generate_flag_contracts.js [--check] [--explain NAME] [--mutate NAME]
//   --check    exit 1 if the checked output differs from what the sources derive (stale gen).
//   --explain  print why NAME got its effect (the call chain to each flag access).
//   --out      write somewhere other than src/rust/gen/flag_contracts.rs (validator self-test).
//   --mutate   NEGATIVE CONTROL ONLY: force NAME to (read=0, write=0). The emitted file says so
//              in a banner and FLAG_CONTRACT_MUTATED is true, so a mutated build is detectable.

import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const __dirname = url.fileURLToPath(new URL(".", import.meta.url));
const ROOT = path.join(__dirname, "..");
const OUT_FILE = path.join(ROOT, "src/rust/gen/flag_contracts.rs");
const SOURCE_DIRS = [path.join(ROOT, "src/rust"), path.join(ROOT, "crates")];

// Tuple order is the builder's slot order (wasm_builder.rs flag_local_get/set).
const FLAG_GLOBALS = ["last_op1", "last_result", "last_op_size", "flags_changed", "flags"];
const FULL = 0x1f;

const KEYWORDS = new Set([
    "if", "while", "match", "for", "return", "fn", "loop", "in", "as", "let", "mut", "move",
    "unsafe", "else", "break", "continue", "where", "impl", "pub", "use", "mod", "struct",
    "enum", "trait", "type", "const", "static", "ref", "self", "Self", "super", "crate", "dyn",
    "extern", "true", "false", "async", "await", "box",
]);

const args = process.argv.slice(2);
const argValue = name => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
const CHECK = args.includes("--check");
const EXPLAIN = argValue("--explain");
const MUTATE = argValue("--mutate");
const WRITE_FILE = argValue("--out") ? path.resolve(argValue("--out")) : OUT_FILE;

function listRustFiles(dir, out = []) {
    if (!fs.existsSync(dir)) return out;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            if (entry.name === "target" || entry.name === "node_modules") continue;
            listRustFiles(p, out);
        }
        else if (entry.name.endsWith(".rs") && p !== OUT_FILE) out.push(p);
    }
    return out.sort();
}

// Blank comments, string and char literals (keeping the quote characters so `extern "C" {`
// still reads as an extern block). Lifetimes are left alone.
function strip(src) {
    let out = "";
    let i = 0;
    const n = src.length;
    while (i < n) {
        const c = src[i], d = src[i + 1];
        if (c === "/" && d === "/") {
            while (i < n && src[i] !== "\n") i++;
            continue;
        }
        if (c === "/" && d === "*") {
            let depth = 1; i += 2;
            while (i < n && depth > 0) {
                if (src[i] === "/" && src[i + 1] === "*") { depth++; i += 2; }
                else if (src[i] === "*" && src[i + 1] === "/") { depth--; i += 2; }
                else i++;
            }
            out += " ";
            continue;
        }
        const prevIdent = i > 0 && /[A-Za-z0-9_]/.test(src[i - 1]);
        if (!prevIdent && (c === "r" || (c === "b" && d === "r")) ) {
            const m = /^b?r(#*)"/.exec(src.slice(i, i + 40));
            if (m) {
                const close = "\"" + m[1];
                const end = src.indexOf(close, i + m[0].length);
                out += "\"\"";
                i = end + close.length;
                continue;
            }
        }
        if (c === "\"" ) {
            i++;
            while (i < n && src[i] !== "\"") i += src[i] === "\\" ? 2 : 1;
            i++;
            out += "\"\"";
            continue;
        }
        if (c === "'") {
            if (d === "\\") {
                i += 2;
                while (i < n && src[i] !== "'") i++;
                i++;
                out += "' '";
                continue;
            }
            if (src[i + 2] === "'") { i += 3; out += "' '"; continue; }
            // lifetime / label
            out += c; i++;
            continue;
        }
        out += c; i++;
    }
    return out;
}

// `if DEBUG { … }` is dead in a release build (dbg.rs: DEBUG = cfg!(debug_assertions)); the
// generated table is only consulted in release builds (see wasm_builder.rs flag_effect).
function dropDebugBlocks(text) {
    for (let m; (m = /\bif\s+(?:crate::dbg::)?DEBUG\s*\{/.exec(text));) {
        const open = m.index + m[0].length - 1;
        const close = matchBrace(text, open);
        text = text.slice(0, m.index) + "{}" + text.slice(close + 1);
    }
    // A `use` names an item without calling it.
    return text.replace(/\buse\s+[^;]*;/g, " ");
}

function matchBrace(text, open) {
    const o = text[open];
    const cl = o === "{" ? "}" : o === "(" ? ")" : "]";
    let depth = 0;
    for (let i = open; i < text.length; i++) {
        if (text[i] === o) depth++;
        else if (text[i] === cl && --depth === 0) return i;
    }
    return text.length - 1;
}

const defs = new Map();        // name -> [{ file, body, sig, exported, traitImpl, isExtern, isMacro }]
const addDef = (name, d) => { if (!defs.has(name)) defs.set(name, []); defs.get(name).push(d); };

for (const file of listRustFiles(SOURCE_DIRS[0]).concat(listRustFiles(SOURCE_DIRS[1]))) {
    const text = dropDebugBlocks(strip(fs.readFileSync(file, "utf8")));
    const rel = path.relative(ROOT, file).replace(/\\/g, "/");

    // extern import blocks and trait-impl blocks, as [start, end] ranges.
    const externRanges = [];
    for (const m of text.matchAll(/\bextern\s+""\s*\{/g)) {
        const open = m.index + m[0].length - 1;
        externRanges.push([open, matchBrace(text, open)]);
    }
    const traitImplRanges = [];
    for (const m of text.matchAll(/\bimpl\b(\s*<[^{;]*?>)?\s+([^{;]*?)\s+for\s+[^{;]*\{/g)) {
        const open = m.index + m[0].length - 1;
        traitImplRanges.push([open, matchBrace(text, open), m[2].trim()]);
    }
    const inRange = (ranges, pos) => ranges.find(r => pos > r[0] && pos < r[1]);

    for (const m of text.matchAll(/\bmacro_rules!\s*([A-Za-z_][A-Za-z0-9_]*)\s*([{(\[])/g)) {
        const open = m.index + m[0].length - 1;
        const close = matchBrace(text, open);
        addDef(m[1] + "!", { file: rel, body: text.slice(open, close + 1), sig: "", exported: false, isMacro: true });
    }

    for (const m of text.matchAll(/\bfn\s+([A-Za-z_][A-Za-z0-9_]*)\s*(<[^(]*?>)?\s*\(/g)) {
        const name = m[1];
        const paramsOpen = m.index + m[0].length - 1;
        const paramsClose = matchBrace(text, paramsOpen);
        let j = paramsClose + 1;
        // Find the body `{` or a `;` (declaration) after the return type / where clause.
        let depthAngle = 0;
        while (j < text.length) {
            const ch = text[j];
            if (ch === "(" || ch === "[") { j = matchBrace(text, j) + 1; continue; }
            if (ch === "<") depthAngle++;
            else if (ch === ">" && text[j - 1] !== "-") depthAngle = Math.max(0, depthAngle - 1);
            else if ((ch === "{" || ch === ";") && depthAngle === 0) break;
            j++;
        }
        const sig = text.slice(m.index, j);
        // The item's own attributes/qualifiers: back to the previous item boundary.
        let k = m.index - 1;
        while (k >= 0 && text[k] !== "}" && text[k] !== ";" && text[k] !== "{") k--;
        const prefix = text.slice(k + 1, m.index);
        const exported = /#\s*\[\s*no_mangle\s*\]/.test(prefix) || /#\s*\[\s*export_name/.test(prefix);
        if (text[j] === ";") {
            if (inRange(externRanges, m.index)) {
                addDef(name, { file: rel, body: "", sig, exported: false, isExtern: true });
            }
            continue;
        }
        const close = matchBrace(text, j);
        const ti = inRange(traitImplRanges, m.index);
        addDef(name, {
            file: rel, body: text.slice(j, close + 1), sig, exported,
            traitImpl: ti ? ti[2] : null,
        });
    }
}

// ---- direct effects and edges, one node per definition ----------------------------------
//
// A node per DEFINITION, not per name: `F80::add` (an operator impl, part of the ambient set)
// must not inherit arith.rs `add`, which writes four flag words. Calls still resolve by name
// to every definition of it, which is the conservative direction.

const nodes = [];             // { name, def, r, w, why, out: Set(node index) }
for (const [name, list] of defs) for (const def of list) nodes.push({ name, def });
const byName = new Map();
nodes.forEach((n, i) => { if (!byName.has(n.name)) byName.set(n.name, []); byName.get(n.name).push(i); });
const crateNames = new Set(defs.keys());

function analyzeBody(def) {
    let r = 0, w = 0;
    const why = [];
    const out = new Set();
    if (def.isExtern) return { r: FULL, w: FULL, why: ["extern import (host may re-enter the CPU)"], out };
    const body = def.body;
    const sig = def.sig;

    if (/\b(fn|Fn|FnMut|FnOnce)\s*\(/.test(sig.replace(/^fn\s+[A-Za-z0-9_]+/, ""))) {
        r = w = FULL; why.push("takes a function value (call target unknown)");
    }
    if (/\)\s*\(|\]\s*\(/.test(body) || /\btransmute\s*::\s*<[^;]*\bfn\b/.test(body) || /\bas\s+fn\s*\(/.test(body) || /:\s*fn\s*\(/.test(body)) {
        r = w = FULL; why.push("indirect call through a value");
    }

    FLAG_GLOBALS.forEach((g, slot) => {
        const bit = 1 << slot;
        const bindRe = new RegExp(String.raw`(\blet\s+(mut\s+)?|[|(,]\s*(mut\s+)?)${g}\s*[:|,)=]`, "g");
        const firstBinding = (() => { const b = bindRe.exec(body); return b ? b.index : Infinity; })();
        const re = new RegExp(String.raw`(\*\s*)?((?:[A-Za-z_][A-Za-z0-9_]*\s*::\s*)*)\b${g}\b`, "g");
        for (const m of body.matchAll(re)) {
            const before = body.slice(Math.max(0, m.index - 6), m.index);
            if (/\.\s*$/.test(before)) continue;                         // field access
            const qualified = /global_pointers\s*::\s*$/.test(m[2]);
            if (m[2] && !qualified) continue;                           // another module's item
            const after = body.slice(m.index + m[0].length, m.index + m[0].length + 4);
            if (/^\s*:(?!:)/.test(after) && !m[1]) continue;             // struct-literal field / type ascription
            if (m[1]) {
                // `&*g` / `&mut *g` borrows the global; `x & *g` is a binary AND (a read).
                if (/(^|[^A-Za-z0-9_)\]\s])\s*&\s*(mut\s*)?$/.test(body.slice(Math.max(0, m.index - 12), m.index))) {
                    r |= bit; w |= bit; why.push(`&*${g} (escapes)`);
                }
                else if (/^\s*=(?!=)/.test(after)) { w |= bit; why.push(`*${g} =`); }
                else if (/^\s*(<<|>>|[-+*/%&|^])=/.test(after)) { r |= bit; w |= bit; why.push(`*${g} op=`); }
                else { r |= bit; why.push(`read *${g}`); }
            }
            else if (qualified || m.index < firstBinding) {
                r |= bit; w |= bit; why.push(`${g} pointer escapes`);
            }
        }
    });

    const locals = new Set();
    const params = sig.slice(sig.indexOf("("));
    for (const m of params.matchAll(/\b([A-Za-z_][A-Za-z0-9_]*)\s*:(?!:)/g)) locals.add(m[1]);
    for (const m of body.matchAll(/\blet\s+(?:mut\s+)?([A-Za-z_][A-Za-z0-9_]*)/g)) locals.add(m[1]);
    for (const m of body.matchAll(/\|\s*(?:mut\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*(?::[^|]*)?\|/g)) locals.add(m[1]);

    // Calls, macro invocations and value references. A path PREFIX (`jit::`, `F80::`) names a
    // module or type, not a function.
    for (const m of body.matchAll(/\b([A-Za-z_][A-Za-z0-9_]*)\b(\s*!\s*[({\[])?(?!\s*::(?!\s*<))/g)) {
        const id = m[1];
        if (KEYWORDS.has(id)) continue;
        if (m[2]) {
            if (crateNames.has(id + "!")) out.add(id + "!");
            continue;
        }
        if (!crateNames.has(id)) continue;
        if (/\bfn\s*$/.test(body.slice(Math.max(0, m.index - 4), m.index))) continue;
        // A local (param/let/closure param) sharing a crate fn's name is not a reference to
        // it, unless it is called: `let foo = foo();` stays an edge.
        if (locals.has(id) && !/^\s*\(/.test(body.slice(m.index + m[0].length, m.index + m[0].length + 3))) continue;
        out.add(id);
    }
    return { r, w, why, out };
}

for (const n of nodes) {
    const a = analyzeBody(n.def);
    n.r = a.r; n.w = a.w;
    n.why = a.why.map(y => `${n.def.file}: ${y}`);
    n.directR = a.r; n.directW = a.w;
    n.out = new Set();
    for (const callee of a.out) for (const i of byName.get(callee)) n.out.add(i);
}

// ---- fixpoint --------------------------------------------------------------------------

const traitImplNodes = nodes.map((n, i) => (n.def.traitImpl ? i : -1)).filter(i => i >= 0);
let ambient = { r: 0, w: 0 };
for (let changed = true; changed;) {
    changed = false;
    for (const n of nodes) {
        let r = n.r | ambient.r, w = n.w | ambient.w;
        for (const c of n.out) { r |= nodes[c].r; w |= nodes[c].w; }
        if (r !== n.r || w !== n.w) { n.r = r; n.w = w; changed = true; }
    }
    const a = { r: 0, w: 0 };
    for (const i of traitImplNodes) { a.r |= nodes[i].r; a.w |= nodes[i].w; }
    if (a.r !== ambient.r || a.w !== ambient.w) { ambient = a; changed = true; }
}
const eff = new Map();
for (const n of nodes) {
    const e = eff.get(n.name) || { r: 0, w: 0 };
    eff.set(n.name, { r: e.r | n.r, w: e.w | n.w });
}

if (EXPLAIN) {
    const seen = new Set();
    const walk = (i, chain) => {
        const n = nodes[i];
        if ((n.r | n.w) === 0 || seen.has(i) || chain.length > 14) return;
        seen.add(i);
        const label = `${n.name}(${n.def.file})`;
        if (n.directR | n.directW) console.log(`${chain.concat(label).join(" -> ")}: ${n.why.join("; ")}`);
        for (const c of n.out) walk(c, chain.concat(label));
    };
    const e = eff.get(EXPLAIN);
    if (!e) { console.error(`no crate fn named ${EXPLAIN}`); process.exit(2); }
    console.log(`${EXPLAIN}: read=0x${e.r.toString(16)} write=0x${e.w.toString(16)} ambient=${JSON.stringify(ambient)}`);
    for (const i of byName.get(EXPLAIN)) walk(i, []);
    process.exit(0);
}

// ---- emit ------------------------------------------------------------------------------

const exported = [...defs].filter(([, l]) => l.some(d => d.exported)).map(([k]) => k).sort();
if (MUTATE && !eff.has(MUTATE)) { console.error(`--mutate: no crate fn named ${MUTATE}`); process.exit(2); }
const rows = [];
for (const name of exported) {
    let { r, w } = eff.get(name);
    if (name === MUTATE) { r = 0; w = 0; }
    if (r === FULL && w === FULL) continue;         // absent == full, the default
    rows.push([name, r, w]);
}
rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

const lines = [];
lines.push("// @generated by gen/generate_flag_contracts.js — do not edit. Regenerate with");
lines.push("// `node gen/generate_flag_contracts.js`; tools/validate-flag-helper-contracts.ts checks freshness.");
if (MUTATE) {
    lines.push("//");
    lines.push(`// !!! NEGATIVE CONTROL: ${MUTATE} is FORCED to (read 0, write 0). NOT A SHIPPABLE BUILD. !!!`);
}
lines.push("//");
lines.push("// (helper, words it may READ, words it may WRITE), bit i = flag-local slot i");
lines.push(`// (${FLAG_GLOBALS.map((g, i) => `${i}=${g}`).join(" ")}). Sorted by name for binary search.`);
lines.push("// A helper that is absent may touch all five in both directions.");
lines.push("");
lines.push(`pub const FLAG_CONTRACT_MUTATED: bool = ${MUTATE ? "true" : "false"};`);
lines.push("");
lines.push(`pub static FLAG_EFFECTS: [(&str, u8, u8); ${rows.length}] = [`);
for (const [n, r, w] of rows) lines.push(`    ("${n}", 0x${r.toString(16).padStart(2, "0")}, 0x${w.toString(16).padStart(2, "0")}),`);
lines.push("];");
lines.push("");
const output = lines.join("\n");

const summary = (() => {
    let pure = 0, readOnly = 0, other = 0;
    for (const [, r, w] of rows) { if (!r && !w) pure++; else if (!w) readOnly++; else other++; }
    return `${exported.length} exported helpers: ${pure} flag-neutral, ${readOnly} read-only, ${other} partial, ${exported.length - rows.length} full (absent)`;
})();

if (CHECK) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : "";
    if (current !== output) {
        console.error(`STALE: ${path.relative(ROOT, OUT_FILE)} does not match what the sources derive. Regenerate it.`);
        process.exit(1);
    }
    console.log(`flag contracts fresh — ${summary}`);
    process.exit(0);
}
fs.writeFileSync(WRITE_FILE, output);
console.log(`wrote ${path.relative(ROOT, WRITE_FILE)} — ${summary}${MUTATE ? ` [MUTATED: ${MUTATE}]` : ""}`);
